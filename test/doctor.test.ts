const fetchOk = async () => ({ ok: true, status: 200, json: async () => ({ pid: 7085, uptime: 259200, identities: {}, spend: {} }) })

const execOk = () => {
  const uid = process.getuid?.()
  return (bin: string, args: string[]) => {
    if (bin === '/bin/launchctl' && args[1]?.endsWith('com.tybarho.claude-router')) throw Object.assign(new Error('not loaded'), { status: 44 })
    if (bin === '/bin/launchctl' && args[1]?.endsWith('dev.barrito.router')) return 'state = running\npid = 7085\n'
    throw new Error(`unexpected: ${bin} ${args.join(' ')}`)
  }
}

