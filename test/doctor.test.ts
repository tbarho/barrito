const shims = (marker = true) => {
  const dir = process.env.BARRITO_SHIMS ?? ''
  mkdirSync(dir, { recursive: true })
  for (const bin of ['claude', 'codex', 'opencode', 'cursor-agent']) {
    writeFileSync(path.join(dir, bin), `#!/bin/sh\n${marker ? '# generated by barrito' : '# hand written'}\nexec real "$@"\n`)
  }
  // rtk and terminal-notifier are on PATH on a healthy machine — doctor probes for both
  writeFileSync(path.join(dir, 'rtk'), '#!/bin/sh\nexec real "$@"\n')
  writeFileSync(path.join(dir, 'terminal-notifier'), '#!/bin/sh\nexec real "$@"\n')
  chmodSync(path.join(dir, 'rtk'), 0o755)
  chmodSync(path.join(dir, 'terminal-notifier'), 0o755)
  rmSync(path.join(dir, 'agent'), { force: true })
  symlinkSync('cursor-agent', path.join(dir, 'agent'))
  // the real harness binaries, so doctor expects a shim for each (never depends on the host PATH)
  const real = realDir()
  mkdirSync(real, { recursive: true })
  for (const bin of ['claude', 'codex', 'opencode', 'cursor-agent']) {
    writeFileSync(path.join(real, bin), '#!/bin/sh\n')
    chmodSync(path.join(real, bin), 0o755)
  }
}

