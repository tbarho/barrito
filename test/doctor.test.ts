const execLinux = (over: { systemctl?: string; loginctl?: string } = {}) => (bin: string, args: string[]) => {
  if (bin === 'systemctl') return over.systemctl ?? 'ActiveState=active\nMainPID=7085\n'
  if (bin === 'loginctl') return over.loginctl ?? 'Linger=yes\n'
  if (bin === 'ps') throw new Error('no ps')
  throw new Error(`unexpected: ${bin} ${args.join(' ')}`)
}

const linuxOpts = (over: Partial<DiagnoseOpts> = {}): DiagnoseOpts => opts({
  exec: execLinux(),
  env: { USER: 'ty', SHELL: '/bin/bash' },
  keyring: () => true,
  ...over,
})

