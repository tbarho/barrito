describe('e2e: generated shim end-to-end (scrubbed env, real git, no real HOME/keychain)', () => {
  const ready = fs.existsSync(join(root, 'src/config.ts')) && fs.existsSync(join(root, 'node_modules/smol-toml'))

  test('shim → barrito env → stub claude with work identity; finds the real bin, never itself; zero git spawns warm', { skip: !ready && 'waiting on src/config.js (workstream D)' }, async (t) => {
    const dir = tmp()
    t.after(() => fs.rmSync(dir, { recursive: true, force: true }))
    const { shims, bin, state, home, repo, gitCount } = setupE2E(dir)

    // env -i equivalent: PATH has the shims dir first and NO node/barrito dir — the baked paths carry those
    const clean = {
      PATH: [shims, dirname(gitCount.wrapper), bin, '/usr/bin', '/bin'].join(':'),
      HOME: home,
      BARRITO_HOME: home,
      BARRITO_CONFIG: join(dir, 'config.toml'),
      BARRITO_STATE: state,
      BARRITO_SHIMS: shims,
      BARRITO_GIT_COUNT: gitCount.file,
      GIT_CONFIG_GLOBAL: '/dev/null',
      GIT_CONFIG_SYSTEM: '/dev/null',
      TMPDIR: os.tmpdir(),
    }

    const barritoJs = join(root, 'bin', 'barrito.ts')
    const gen = spawnSync(process.execPath, [barritoJs, 'shim', 'claude', '--dir', shims], { encoding: 'utf8', env: clean })
    assert.equal(gen.status, 0, gen.stderr)
    const shimBody = fs.readFileSync(join(shims, 'claude'), 'utf8')
    assert.ok(shimBody.includes(`eval "$(${JSON.stringify(process.execPath)} ${JSON.stringify(fs.realpathSync(barritoJs))} env --shell --harness claude --self "$0")"`), shimBody)

    const reads = () => {
      try { return Number(fs.readFileSync(gitCount.file, 'utf8').trim()) } catch { return 0 }
    }
    const out = (r: { stdout: string }): Record<string, string> => Object.fromEntries(r.stdout.trim().split('\n').map((l: string) => l.split('=')))

    const before = reads()
    const cold = spawnSync('claude', [], { encoding: 'utf8', cwd: repo, env: clean, shell: true }) // resolves via PATH
    assert.equal(cold.status, 0, cold.stderr)
    const coldSpawns = reads() - before
    assert.equal(coldSpawns, 3, `cold run should make exactly 3 git spawns (top, remote, commondir), made ${coldSpawns}`)
    const coldEnv = out(cold)
    assert.equal(coldEnv.BASE, 'http://127.0.0.1:4141')
    assert.equal(coldEnv.CFG, join(home, '.claude-work'))
    assert.equal(coldEnv.HDR, 'x-barrito-identity: work')
    assert.equal(coldEnv.ID, 'work')
    assert.equal(coldEnv.REAL, fs.realpathSync(join(bin, 'claude'))) // the stub, never the shim

    const beforeWarm = reads()
    const warm = spawnSync('claude', [], { encoding: 'utf8', cwd: repo, env: clean, shell: true })
    assert.equal(warm.status, 0, warm.stderr)
    assert.equal(reads() - beforeWarm, 0, 'warm run must make zero git spawns (cache hit, graft served from cache)')
    assert.deepEqual(out(warm), coldEnv)

    const cache: unknown = JSON.parse(fs.readFileSync(join(state, 'which.json'), 'utf8'))
    assert.ok(isRecord(cache))
    assert.ok(isRecord(cache.repos))
    assert.ok(isRecord(cache.dirs))
    const entry = cache.repos[String(cache.dirs[fs.realpathSync(repo)])]
    assert.ok(isRecord(entry))
    const result = entry.result
    assert.ok(isRecord(result))
    assert.equal(result.id, 'work')
    assert.equal(result.rule, 'remote')
    assert.equal(entry.configFile, join(fs.realpathSync(repo), '.git', 'config'))

    const whichRun = spawnSync(process.execPath, [barritoJs, 'which'], { encoding: 'utf8', cwd: repo, env: clean })
    assert.match(whichRun.stdout.trim(), /^work  ← remote github\.com\/acme\/x$/)
  })
})

const setupE2E = (dir: string) => {
  const shims = join(dir, 'shims')
  const bin = join(dir, 'bin')
  const state = join(dir, 'state')
  const home = join(dir, 'home')
  const repo = join(dir, 'repo')
  for (const d of [bin, state, home, repo]) fs.mkdirSync(d, { recursive: true })

  stubBin(bin, 'claude', [
    'echo "BASE=$ANTHROPIC_BASE_URL"',
    'echo "CFG=$CLAUDE_CONFIG_DIR"',
    'echo "HDR=$ANTHROPIC_CUSTOM_HEADERS"',
    'echo "ID=$BARRITO_IDENTITY"',
    'echo "REAL=$BARRITO_REAL_BIN"',
  ].join('\n'))

  // PATH git wrapper that counts spawns, then forwards to the real git
  const gitDir = join(dir, 'gitwrap')
  const gitCount = { file: join(dir, 'git-count'), wrapper: stubBin(gitDir, 'git', `c=$(cat "$BARRITO_GIT_COUNT" 2>/dev/null || echo 0)\necho $((c + 1)) > "$BARRITO_GIT_COUNT"\nexec "${spawnSync('which', ['git'], { encoding: 'utf8' }).stdout.trim()}" "$@"`) }

  const gitEnv = { ...process.env, HOME: home, GIT_CONFIG_GLOBAL: '/dev/null', GIT_CONFIG_SYSTEM: '/dev/null' }
  execFileSync('git', ['init', '-q', repo], { env: gitEnv })
  execFileSync('git', ['-C', repo, 'remote', 'add', 'origin', 'git@github.com:acme/x.git'], { env: gitEnv })

  fs.writeFileSync(join(dir, 'config.toml'), `\
port = 4141
default = "personal"

[identities.work]
claude_config_dir = "${join(home, '.claude-work')}"

[identities.work.match]
remotes = ["github.com/acme/*"]

[identities.personal]
claude_config_dir = "${join(home, '.claude-personal')}"

[identities.personal.match]
remotes = ["github.com/you/*"]
`)
  return { shims, bin, state, home, repo, gitCount }
}
