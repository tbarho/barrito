const root = resolvePath(dirname(fileURLToPath(import.meta.url)), '..')
const MARKER = 'generated by barrito'

const tmp = () => fs.mkdtempSync(join(os.tmpdir(), 'barrito-shim-'))

const ctx = (config: Config): CommandCtx & { lines: string[]; errors: string[]; code: number | null } => {
  const lines: string[] = []
  const errors: string[] = []
  let code: number | null = null
  return {
    config,
    lines,
    errors,
    get code() { return code },
    print: (line: string) => { lines.push(line) },
    exit: (status: number) => { code = status },
  }
}

const config: Config = {
  default: 'work',
  port: 4141,
  identities: {
    work: {
      id: 'work',
      claude_config_dir: "/tmp/barrito-it's/.claude",
      share_from: null,
      fallback: [],
      match: { remotes: [], paths: [] },
      keychain: { cursor: 'Cursor Work' },
    },
  },
  models: { include: [], exclude: [], require: [], max_input_price: null, pin: [], labels: {}, agents: {} },
  graft: { roots: [], repos: [] },
  harness: { mybot: { bin: 'mybot', env: { OPENAI_BASE_URL: '{gateway}/v1', OPENAI_API_KEY: '{handle}' } } },
}

const withEnv = (t: TestContext, vars: Record<string, string | undefined>, fn: () => Promise<void>): Promise<void> => {
  const saved: Record<string, string | undefined> = {}
  for (const k of Object.keys(vars)) {
    saved[k] = process.env[k]
    if (vars[k] === undefined) delete process.env[k]
    else process.env[k] = vars[k]
  }
  t.after(() => {
    for (const k of Object.keys(saved)) {
      if (saved[k] === undefined) delete process.env[k]
      else process.env[k] = saved[k]
    }
  })
  return fn()
}

const stubBin = (dir: string, name: string, body = '#!/usr/bin/env bash\ntrue\n'): string => {
  fs.mkdirSync(dir, { recursive: true })
  const file = join(dir, name)
  fs.writeFileSync(file, `#!/usr/bin/env bash\n${body}\n`)
  fs.chmodSync(file, 0o755)
  return file
}

const baked = (): string => `${JSON.stringify(process.execPath)} ${JSON.stringify(fs.realpathSync(process.argv[1]!))}`

const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === 'object' && value !== null && !Array.isArray(value)

describe('barrito shim (unit)', () => {
  test('writes exec-able marker files with baked paths + --self, and alias symlinks', async (t) => {
    const dir = tmp()
    t.after(() => fs.rmSync(dir, { recursive: true, force: true }))
    const c = ctx(config)
    await shim(['claude', 'cursor-agent', 'mybot', '--dir', dir], c)
    assert.equal(c.code, null)
    for (const name of ['claude', 'cursor-agent', 'mybot']) {
      const body = fs.readFileSync(join(dir, name), 'utf8')
      assert.ok(body.includes(MARKER))
      assert.ok(body.includes(`eval "$(${baked()} env --shell --harness ${name} --self "$0")" || exit $?`), body)
      assert.ok(body.includes('[ -n "${BARRITO_REAL_BIN:-}" ] || exit 127'))
      assert.ok(body.includes('exec "$BARRITO_REAL_BIN" "$@"'))
      assert.equal(fs.statSync(join(dir, name)).mode & 0o111, 0o111)
    }
    assert.equal(fs.readlinkSync(join(dir, 'agent')), 'cursor-agent')
  })

  test('no args = all builtins + config harnesses', async (t) => {
    const dir = tmp()
    t.after(() => fs.rmSync(dir, { recursive: true, force: true }))
    const c = ctx(config)
    await shim(['--dir', dir], c)
    for (const name of ['claude', 'codex', 'opencode', 'cursor-agent', 'mybot', 'agent']) {
      assert.ok(fs.existsSync(join(dir, name)), name)
    }
  })

  test('regenerating a marked file is fine', async (t) => {
    const dir = tmp()
    t.after(() => fs.rmSync(dir, { recursive: true, force: true }))
    await shim(['claude', '--dir', dir], ctx(config))
    const c = ctx(config)
    await shim(['claude', '--dir', dir], c)
    assert.equal(c.code, null)
  })

  test('refuses to overwrite foreign files, lists them, changes nothing', async (t) => {
    const dir = tmp()
    t.after(() => fs.rmSync(dir, { recursive: true, force: true }))
    fs.writeFileSync(join(dir, 'claude'), 'my hand-written shim\n')
    const err = t.mock.method(console, 'error', () => {})
    const c = ctx(config)
    await shim(['claude', '--dir', dir], c)
    assert.equal(c.code, 1)
    assert.equal(fs.readFileSync(join(dir, 'claude'), 'utf8'), 'my hand-written shim\n')
    assert.ok(err.mock.calls.some((call) => String(call.arguments[0]).includes(join(dir, 'claude'))))
  })

  test('a foreign file at an alias path is also protected', async (t) => {
    const dir = tmp()
    t.after(() => fs.rmSync(dir, { recursive: true, force: true }))
    fs.writeFileSync(join(dir, 'agent'), '#!/bin/sh\nmy agent wrapper\n')
    t.mock.method(console, 'error', () => {})
    const c = ctx(config)
    await shim(['cursor-agent', '--dir', dir], c)
    assert.equal(c.code, 1)
    assert.ok(!fs.existsSync(join(dir, 'cursor-agent')))
  })

  test('--force overwrites foreign files', async (t) => {
    const dir = tmp()
    t.after(() => fs.rmSync(dir, { recursive: true, force: true }))
    fs.writeFileSync(join(dir, 'claude'), 'custom\n')
    const c = ctx(config)
    await shim(['claude', '--dir', dir, '--force'], c)
    assert.equal(c.code, null)
    assert.ok(fs.readFileSync(join(dir, 'claude'), 'utf8').includes(MARKER))
  })

  test('unknown harness → exit 2', async () => {
    const c = ctx(config)
    await shim(['nope', '--dir', tmp()], c)
    assert.equal(c.code, 2)
  })
})

