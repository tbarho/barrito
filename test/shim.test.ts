      await env([], c)
      const logged = err.mock.calls.map((call) => String(call.arguments[0])).join('\n')
      assert.ok(logged.includes('work ← env BARRITO_IDENTITY'))
      assert.ok(logged.includes('ANTHROPIC_BASE_URL=<redacted:'))
